-- 008_settings.sql — 사람이 화면에서 고치는 사이트 문구를 담는다.
--
-- # 왜 필요한가
--
-- 홈 표제지의 세 줄(눈썹줄·제목·리드)이 `templates/home.html`에 박혀 있었다.
-- 그 문구를 고치려면 코드를 고쳐 배포해야 하는데, **글은 웹에서 쓰고 고친다**는
-- 이 프로젝트의 전제와 어긋난다. 홈에 서는 문장도 결국 글이다.
--
-- # 왜 posts가 아닌가
--
-- 홈 문구는 주소도 없고 목록에도 안 서고 분류도 없다. posts에 넣으면
-- 사이트맵·목록·검색·표지 판정이 전부 "이건 예외"를 하나씩 더 들어야 한다.
-- 한 줄짜리 값 몇 개를 담는 자리는 그냥 key-value가 맞다.
--
-- # 왜 값마다 행인가
--
-- JSON 한 덩어리로 두면 두 화면이 동시에 저장할 때 나중 것이 앞의 것을 통째로
-- 지운다. 행으로 나누면 서로 다른 값을 건드리는 저장끼리는 안 부딪힌다.
--
-- # 기본값은 여기 안 넣는다
--
-- 행이 없으면 코드의 기본값을 쓴다(`internal/web/settings.go`). 그래야
-- **처음 뜨는 사이트도 문구가 있고**, 사람이 안 건드린 문구를 나중에 코드에서
-- 다듬을 수 있다. 여기에 INSERT해 두면 그 순간부터 그 값이 정본이 되어,
-- 아무도 고친 적 없는 문장이 DB에 굳는다.

CREATE TABLE settings (
    key        TEXT PRIMARY KEY,
    value      TEXT NOT NULL,
    updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);
