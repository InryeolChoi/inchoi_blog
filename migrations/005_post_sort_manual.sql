-- 005_post_sort_manual.sql — "이 순서는 사람이 정했다"를 DB에 적어둔다.
--
-- # 왜 필요한가
--
-- 웹은 sort_order를 **믿지 않는다**. 1,356편 중 708편의 sort_order가
-- created_time 순위에서 나왔는데 그 값이 분 단위라, 한 번에 만든 글들이 같은
-- 값을 갖고 순서가 자주 어긋난다. 그래서 web.sortPosts가 제목 앞 번호와 자연
-- 정렬로 화면 순서를 다시 세운다.
--
-- 문제는 **사람이 직접 정한 순서까지 그 불신에 휩쓸린다**는 것이다.
-- curation.PostMetadataEdits에 순서를 적고 sortorder로 반영해도, 제목에 번호가
-- 없으면 화면은 가나다순으로 세워 버린다. 실제로 `다변량분석 : 코드` 12편이
-- 그랬다 — DB는 0~11인데 화면은 "군집분석 → 다변량분석? → 대응분석 …"이었다.
--
-- # 왜 코드가 아니라 컬럼인가
--
-- 웹이 internal/curation을 직접 읽게 하면, 같은 DB를 다른 바이너리로 서빙할 때
-- 순서가 달라진다. **DB가 정본이라는 전제가 거기서 깨진다.** 순서를 누가 정했나는
-- 데이터의 성질이므로 데이터가 들고 있어야 한다.
--
-- # 왜 불리언인가
--
-- "출처"를 그대로 적는 편(childpage/created/manual)이 더 풍부하지만, 그러면
-- sortorder가 1,356행 전부에 값을 채워야 하고 그 값이 실제로 쓰이는 자리는
-- 지금 하나뿐이다. 지금 답해야 하는 질문은 "이 값을 믿어도 되나" 하나다.
-- 나중에 출처가 더 필요해지면 컬럼을 하나 더 더한다 — 이 프로젝트는 컬럼을
-- 지우지 않으므로, 좁게 시작하는 편이 되돌리기 쉽다.
--
-- 기본값 0이라 기존 1,356행은 예전과 똑같이 다뤄진다.
ALTER TABLE posts ADD COLUMN sort_order_manual INTEGER NOT NULL DEFAULT 0;
